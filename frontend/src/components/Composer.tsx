import { useEffect, useRef, useState } from 'react'

export function Composer({ onSubmit, busy }: { onSubmit: (q: string) => void; busy: boolean }) {
  const [text, setText] = useState('')
  const ref = useRef<HTMLTextAreaElement>(null)

  useEffect(() => {
    const el = ref.current
    if (!el) return
    el.style.height = 'auto'
    el.style.height = `${Math.min(el.scrollHeight, 140)}px`
  }, [text])

  const send = () => {
    const q = text.trim()
    if (q.length < 3 || busy) return
    onSubmit(q)
    setText('')
  }

  return (
    <div className="composer-wrap">
      <form className="composer" onSubmit={(e) => { e.preventDefault(); send() }}>
        <textarea
          ref={ref}
          rows={1}
          value={text}
          maxLength={500}
          placeholder="Ask about your sales… e.g. What sold best last weekend?"
          aria-label="Ask a question about your sales"
          onChange={(e) => setText(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === 'Enter' && !e.shiftKey && !e.nativeEvent.isComposing) {
              e.preventDefault()
              send()
            }
          }}
        />
        <button className="send" type="submit" disabled={busy || text.trim().length < 3} aria-label="Send question">
          ASK
        </button>
      </form>
      <div className="footnote">Answers are generated by AI from synthetic demo data. Check the query before relying on a number.</div>
    </div>
  )
}
