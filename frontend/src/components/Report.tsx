import { useEffect } from 'react'
import { createPortal } from 'react-dom'
import { chartImage, downloadBlob, filename } from '../exporters'
import { columnKind, fmtCell, humanize, isMonthly } from '../format'
import type { Turn } from '../types'
import { LogoMark, Wordmark } from './Logo'
import { ResultChart } from './ResultChart'

export type ExportAction = 'png' | 'jpeg' | 'pdf'
export interface ExportJob {
  turn: Turn
  action: ExportAction
  storeName: string
}

const ROWS = 25
const today = () => new Date().toLocaleDateString('en-AU', { day: 'numeric', month: 'long', year: 'numeric' })

/** One page for one answer: question, answer, chart, table, query. Always light, so it prints and pastes cleanly. */
function Report({ turn, storeName }: { turn: Turn; storeName: string }) {
  const r = turn.result!
  const hasChart = !!r.chart && r.rows.length > 1
  const kinds = r.columns.map((c, i) => columnKind(c, r.rows.map((row) => row[i])))
  const monthly = r.columns.map((_, i) => isMonthly(r.rows.map((row) => row[i])))
  const numeric = r.columns.map((_, i) => r.rows.some((row) => typeof row[i] === 'number'))
  const shown = r.rows.slice(0, ROWS)
  return (
    <div className="report">
      <header className="report-head">
        <div className="brand"><LogoMark size={26} /><Wordmark /></div>
        <span>{storeName} · {today()}</span>
      </header>
      <h1 className="report-q">{turn.question}</h1>
      <p className="report-a">{r.answer}</p>
      {r.assumptions && <div className="note"><span><b>How this was read: </b>{r.assumptions}</span></div>}
      {hasChart && <div className="report-chart"><ResultChart result={r} animate={false} compact /></div>}
      {r.rows.length > 0 && (
        <>
          <table className="report-table">
            <thead><tr>{r.columns.map((c, i) => <th key={c} className={numeric[i] ? 'num' : ''}>{humanize(c)}</th>)}</tr></thead>
            <tbody>
              {shown.map((row, ri) => (
                <tr key={ri}>{row.map((v, ci) => (
                  <td key={ci} className={numeric[ci] ? 'num' : ''}>{fmtCell(v, kinds[ci], monthly[ci])}</td>
                ))}</tr>
              ))}
            </tbody>
          </table>
          {r.rows.length > ROWS && <p className="report-more">Showing the first {ROWS} of {r.rows.length.toLocaleString()} rows. Download the CSV for the rest.</p>}
        </>
      )}
      {r.sql && (
        <div className="report-query">
          <h2 className="report-h2">The query behind this answer</h2>
          <pre className="report-sql">{r.sql}</pre>
        </div>
      )}
      <footer className="report-foot">
        Generated by MarginAI from {storeName}’s data{r.model ? ` using ${r.model}` : ''}. AI-written answers can contain
        mistakes: check the query and any figure you rely on.
      </footer>
    </div>
  )
}

function printReport(name: string): Promise<void> {
  return new Promise((resolve) => {
    const old = document.title
    document.title = name.replace(/\.pdf$/, '') // Chrome and Safari suggest the page title as the PDF's file name
    const done = () => {
      document.title = old
      window.removeEventListener('afterprint', done)
      resolve()
    }
    window.addEventListener('afterprint', done)
    window.print()
    setTimeout(done, 120_000) // a browser that never reports afterprint must not leave the title changed
  })
}

async function exportImage(job: ExportJob, format: 'png' | 'jpeg'): Promise<void> {
  const host = document.getElementById('print-root')!
  const svg = host.querySelector<SVGSVGElement>('.report-chart svg.recharts-surface')
  if (!svg) throw new Error('There is no chart to export for this answer.')
  const legend = [...host.querySelectorAll<HTMLElement>('.report-chart .legend span')].map((el) => ({
    color: getComputedStyle(el.querySelector('i')!).backgroundColor, label: el.textContent ?? '',
  }))
  const title = host.querySelector('.report-chart .chart-title')?.textContent ?? ''
  const blob = await chartImage({
    svg, legend, format, title: job.turn.question, subtitle: title,
    footer: `${job.storeName} · ${today()} · MarginAI`,
  })
  downloadBlob(blob, filename(job.turn.question, format === 'jpeg' ? 'jpg' : 'png'))
}

/** Renders the report off-screen (or for printing) when an export is requested, runs it, then removes it. */
export function ReportHost({ job, onDone, onError }: {
  job: ExportJob | null
  onDone: () => void
  onError: (message: string) => void
}) {
  useEffect(() => {
    if (!job) return
    let cancelled = false
    ;(async () => {
      await new Promise((r) => setTimeout(r, 400)) // let the chart lay itself out at the report's fixed width
      if (cancelled) return
      try {
        if (job.action === 'pdf') await printReport(filename(job.turn.question, 'pdf'))
        else await exportImage(job, job.action)
      } catch (e) {
        onError((e as Error).message)
      } finally {
        if (!cancelled) onDone()
      }
    })()
    return () => { cancelled = true }
  }, [job, onDone, onError])

  return job?.turn.result ? createPortal(<div id="print-root"><Report turn={job.turn} storeName={job.storeName} /></div>, document.body) : null
}
